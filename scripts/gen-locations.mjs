// Regenerates src/renderer/src/lib/locations.data.ts from country-state-city.
// Run: node scripts/gen-locations.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import pkg from 'country-state-city'

const { City, State, Country } = pkg
const here = dirname(fileURLToPath(import.meta.url))

const WORK = ['Remote', 'Remote (US)', 'Hybrid', 'On-site']

const countryName = new Map()
for (const c of Country.getAllCountries()) countryName.set(c.isoCode, c.name)

const stateName = new Map()
for (const s of State.getAllStates()) stateName.set(`${s.countryCode}:${s.isoCode}`, s.name)

const seen = new Set()
const out = []
for (const c of City.getAllCities()) {
  const cc = c.countryCode
  const st = stateName.get(`${cc}:${c.stateCode}`)
  let label
  if (cc === 'US') {
    label = st ? `${c.name}, ${st}` : c.name
  } else {
    const country = countryName.get(cc) ?? cc
    label = st ? `${c.name}, ${st}, ${country}` : `${c.name}, ${country}`
  }
  if (seen.has(label)) continue
  seen.add(label)
  out.push(label)
}

const US_STATES = new Set(State.getAllStates().filter((s) => s.countryCode === 'US').map((s) => s.name))
// US cities first (so a domestic namesake surfaces above far-flung ones), then the rest.
const isUs = (l) => US_STATES.has(l.split(', ').slice(1).join(', '))
const us = out.filter(isUs).sort()
const world = out.filter((l) => !isUs(l)).sort()
const all = [...WORK, ...us, ...world]

const body =
  '// GENERATED by scripts/gen-locations.mjs — do not edit by hand.\n' +
  '/* eslint-disable */\n' +
  `export const LOCATIONS: string[] = ${JSON.stringify(all)}\n`

writeFileSync(join(here, '../src/renderer/src/lib/locations.data.ts'), body)
console.log(`wrote ${all.length} locations`)
